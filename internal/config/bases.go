package config

import (
	"fmt"
	"regexp"
	"slices"
	"strings"
	"sync"

	"github.com/remyz17/odooboat/images"
)

// BasesPath locates the published base images in the repository and in
// provenance (ADR 0008 A3).
const BasesPath = "images/bases.yaml"

type basesDocument struct {
	Schema int                          `yaml:"schema"`
	Bases  map[string]map[string]string `yaml:"bases"`
}

// Bases maps a series and Python version to its published base image, pinned
// by digest. The images CI writes it after each publication.
type Bases struct {
	images map[string]map[string]string
	ref    docRef
}

// Lookup returns the published base of a series and Python version and where
// it is recorded, for provenance.
func (b Bases) Lookup(series, python string) (string, SourceRef, bool) {
	image, ok := b.images[series][python]
	if !ok {
		return "", SourceRef{}, false
	}
	return image, b.ref.ref("bases." + series + "." + python), true
}

// With returns a copy recording image as the base of series and python.
func (b Bases) With(series, python, image string) Bases {
	out := Bases{images: map[string]map[string]string{}, ref: b.ref}
	for s, byPython := range b.images {
		out.images[s] = map[string]string{}
		for p, ref := range byPython {
			out.images[s][p] = ref
		}
	}
	if out.images[series] == nil {
		out.images[series] = map[string]string{}
	}
	out.images[series][python] = image
	return out
}

// publishedRe is a registry reference pinned by digest. A local image ID is
// accepted in configuration only, never as a published base.
var publishedRe = regexp.MustCompile(`^[a-z0-9][a-z0-9._/:-]*@sha256:[0-9a-f]{64}$`)

const basesHeader = `# Published base images (ADR 0008 §13, amendment A3). Generated by
# ` + "`go run ./images/ci bases`" + ` after each publication; do not edit by hand.
# Each entry pins the multi-arch image of one series and Python version.
`

// Format renders the document deterministically, so a regenerated file only
// differs where an image changed.
func (b Bases) Format() []byte {
	var out strings.Builder
	out.WriteString(basesHeader)
	out.WriteString("schema: 1\n")
	if len(b.images) == 0 {
		out.WriteString("bases: {}\n")
		return []byte(out.String())
	}
	out.WriteString("bases:\n")
	series := sortedKeys(b.images)
	slices.SortFunc(series, compareSeries)
	for _, s := range series {
		fmt.Fprintf(&out, "  %q:\n", s)
		pythons := sortedKeys(b.images[s])
		slices.SortFunc(pythons, comparePython)
		for _, p := range pythons {
			fmt.Fprintf(&out, "    %q: %s\n", p, b.images[s][p])
		}
	}
	return []byte(out.String())
}

var embeddedBases = sync.OnceValues(func() (Bases, error) {
	matrix, err := EmbeddedMatrix()
	if err != nil {
		return Bases{}, err
	}
	return ParseBases(images.Bases, matrix)
})

// EmbeddedBases returns the published bases compiled into this binary.
func EmbeddedBases() (Bases, error) { return embeddedBases() }

// ParseBases strictly decodes the published bases and checks every entry
// against the matrix: a base exists only for a supported series and Python.
func ParseBases(data []byte, matrix Matrix) (Bases, error) {
	doc, err := decodeBytes[basesDocument](SourceBases, BasesPath, data)
	if err != nil {
		return Bases{}, err
	}
	ref := doc.as(SourceBases)
	c := &collector{}
	if doc.doc.Schema != 1 {
		c.addField(ErrAuthored, "schema", ref.ref("schema"), "unsupported bases schema", fmt.Sprint(doc.doc.Schema), "this binary reads schema 1")
	}
	b := Bases{images: map[string]map[string]string{}, ref: ref}
	for _, series := range sortedKeys(doc.doc.Bases) {
		entry, known := matrix.Lookup(series)
		if !known {
			c.addField(ErrAuthored, FieldPath("bases."+series), ref.ref("bases."+series), "series is not in the matrix", series, "")
			continue
		}
		b.images[series] = map[string]string{}
		for _, python := range sortedKeys(doc.doc.Bases[series]) {
			image := doc.doc.Bases[series][python]
			field := "bases." + series + "." + python
			switch {
			case !slices.Contains(entry.Python, python):
				c.addField(ErrAuthored, FieldPath(field), ref.ref(field), "python version is not supported for this series", python, "")
			case !publishedRe.MatchString(image):
				c.addField(ErrAuthored, FieldPath(field), ref.ref(field), "a published base must be pinned by digest", image, "")
			default:
				b.images[series][python] = image
			}
		}
	}
	if err := c.err(); err != nil {
		return Bases{}, err
	}
	return b, nil
}

// comparePython orders "3.9" before "3.10".
func comparePython(a, b string) int {
	var aMajor, aMinor, bMajor, bMinor int
	_, _ = fmt.Sscanf(a, "%d.%d", &aMajor, &aMinor)
	_, _ = fmt.Sscanf(b, "%d.%d", &bMajor, &bMinor)
	if aMajor != bMajor {
		return aMajor - bMajor
	}
	return aMinor - bMinor
}
